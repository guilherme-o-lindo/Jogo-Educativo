import { describe, expect, it } from 'vitest'
import { applyHardwareAction, createHardwareCase, isHardwareResolved, type HardwareState, type CableId, type SlotId } from './hardware'

function act(state: HardwareState, action: Parameters<typeof applyHardwareAction>[1]) {
  return applyHardwareAction(state, action)
}

function connect(state: HardwareState, cable: CableId, first: string, second: string) {
  return act(act(state, { type: 'connect', cable, connector: first }), { type: 'connect', cable, connector: second })
}
function prepare(state: HardwareState) {
  return act(act(state, { type: 'setPsu', on: false }), { type: 'disconnect', cable: 'ac' })
}

describe('bancada de hardware', () => {
  it('reserva PWR_SW para o botão conectado ou para a chave com os pinos livres', () => {
    let state = createHardwareCase('video')
    state = act(state, { type: 'setPsu', on: true })
    const occupied = act(state, { type: 'pressPower', method: 'bridge' })
    expect(occupied.lastTest).toBeNull()
    expect(occupied.powered).toBe(false)
    expect(occupied.feedback).toMatch(/ocupados/i)
    state = act(state, { type: 'setPsu', on: false })
    state = act(state, { type: 'disconnect', cable: 'ac' })
    state = act(state, { type: 'disconnectEnd', cable: 'front_panel', connector: 'mb_pwr_sw' })
    state = act(state, { type: 'pressPower', method: 'button' })
    expect(state.lastTest).toBeNull()
    expect(state.feedback).toMatch(/livres/i)
    state = act(state, { type: 'connect', cable: 'ac', connector: 'wall_ac' })
    state = act(state, { type: 'connect', cable: 'ac', connector: 'psu_ac' })
    state = act(state, { type: 'setPsu', on: true })
    state = act(state, { type: 'pressPower', method: 'bridge' })
    expect(state.lastTest?.method).toBe('bridge')
    expect(state.lastTest?.code).toBe('dram_error')
  })
  it('guarda a localização de reposições e peças retiradas sem alterar a posição da baia', () => {
    let state = createHardwareCase('storage')
    state = act(state, { type: 'takePart', part: 'ssd_sata_good' })
    expect(state.looseLocations).toEqual(['tray'])
    state = act(state, { type: 'disconnect', cable: 'ac' })
    state = act(state, { type: 'moveLoose', index: 0, x: 740, y: 570, location: 'table' })
    expect(state.looseLocations).toEqual(['table'])
    expect(state.loosePositions[0]).toEqual({ x: 740, y: 570 })
    state = act(state, { type: 'moveLoose', index: 0, x: 740, y: 570, location: 'tray' })
    expect(state.looseLocations).toEqual(['tray'])
    state = act(state, { type: 'disconnect', cable: 'sata_data' })
    state = act(state, { type: 'disconnect', cable: 'sata_power' })
    state = act(state, { type: 'remove', slot: 'sata_bay' })
    expect(state.looseLocations).toEqual(['tray', 'tray'])
    expect(state.objects.ssd).toEqual({ x: 965, y: 450 })
  })

  it('retira o SSD após soltar suas portas, mantendo as outras pontas conectadas', () => {
    let state = prepare(createHardwareCase('video'))
    state = act(state, { type: 'disconnectEnd', cable: 'sata_data', connector: 'disk_data' })
    state = act(state, { type: 'disconnectEnd', cable: 'sata_power', connector: 'disk_power' })
    state = act(state, { type: 'remove', slot: 'sata_bay' })
    expect(state.parts.sata_bay).toBeNull()
    expect(state.connections.sata_data).toEqual(['mb_sata1'])
    expect(state.connections.sata_power).toEqual(['psu_sata'])
  })
  it('instala o exemplar arrastado quando há peças iguais na bandeja e na mesa', () => {
    let state = act(createHardwareCase('video'), { type: 'disconnect', cable: 'ac' })
    state = act(state, { type: 'takePart', part: 'ram_good' })
    state = act(state, { type: 'takePart', part: 'ram_good' })
    state = act(state, { type: 'moveLoose', index: 1, x: 680, y: 550, location: 'table' })
    state = act(state, { type: 'install', part: 'ram_good', slot: 'dimm_b2', index: 1 })
    expect(state.inventory).toEqual(['ram_good'])
    expect(state.looseLocations).toEqual(['tray'])
    expect(state.parts.dimm_b2).toBe('ram_good')
  })
  it.each([
    ['cooler', ['cpu_fan']], ['cpu', ['cpu_fan']], ['dimm_a2', []],
    ['pcie_x16', ['hdmi']], ['sata_bay', ['sata_data', 'sata_power']], ['front_button', []],
  ] as [SlotId, CableId[]][])('retira e reinstala %s sem duplicar a peça e respeita o bloqueio elétrico', (slot, cables) => {
    let state = createHardwareCase('video')
    const part = state.parts[slot]!
    const blocked = act(state, { type: 'remove', slot })
    expect(blocked.parts[slot]).toBe(part)
    expect(blocked.inventory).toHaveLength(0)
    state = act(state, { type: 'disconnect', cable: 'ac' })
    for (const cable of cables) state = act(state, { type: 'disconnect', cable })
    if (slot === 'cpu') state = act(state, { type: 'remove', slot: 'cooler' })
    state = act(state, { type: 'remove', slot })
    expect(state.parts[slot]).toBeNull()
    expect(state.inventory.filter(item => item === part)).toHaveLength(1)
    expect(state.looseLocations.at(-1)).toBe('tray')
    state = act(state, { type: 'install', part, slot, index: state.inventory.length - 1 })
    expect(state.parts[slot]).toBe(part)
    expect(state.inventory.filter(item => item === part)).toHaveLength(0)
  })
  it('instala e remove RAM nos dois encaixes aceitos', () => {
    let state = createHardwareCase('video')
    state = act(state, { type: 'disconnect', cable: 'ac' })
    state = act(state, { type: 'remove', slot: 'dimm_a2' })
    state = act(state, { type: 'takePart', part: 'ram_good' })
    state = act(state, { type: 'install', part: 'ram_good', slot: 'dimm_b2' })
    expect(state.parts.dimm_a2).toBeNull()
    expect(state.parts.dimm_b2).toBe('ram_good')
    state = act(state, { type: 'remove', slot: 'dimm_b2' })
    state = act(state, { type: 'install', part: 'ram_good', slot: 'dimm_a2' })
    expect(state.parts.dimm_a2).toBe('ram_good')
    expect(state.parts.dimm_b2).toBeNull()
  })
  it('atualiza objetos durante o gesto sem poluir o histórico e registra o rompimento uma vez', () => {
    let state = createHardwareCase('video')
    state = act(state, { type: 'disconnect', cable: 'ac' })
    const before = state.journal.length
    state = act(state, { type: 'moveObject', object: 'psu', x: 115, y: 395, transient: true })
    expect(state.objects.psu.y).toBe(395)
    expect(state.journal).toHaveLength(before)
    state = act(state, { type: 'moveObject', object: 'psu', x: 1210, y: 385, transient: true })
    expect(state.cables.eps8.condition).toBe('broken')
    expect(state.journal).toHaveLength(before + 1)
  })

  it('move uma ponta solta e conecta somente a ponta compatível', () => {
    let state = createHardwareCase('video')
    state = act(state, { type: 'disconnect', cable: 'ac' })
    state = act(state, { type: 'disconnectEnd', cable: 'atx24', connector: 'mb_atx24' })
    expect(state.connections.atx24).toEqual(['psu_atx24'])
    const before = state.journal.length
    state = act(state, { type: 'moveCableEnd', cable: 'atx24', connector: 'mb_atx24', x: 500, y: 350, transient: true })
    expect(state.cableEnds.atx24.mb_atx24).toEqual({ x: 500, y: 350 })
    expect(state.journal).toHaveLength(before)
    state = act(state, { type: 'connect', cable: 'atx24', connector: 'mb_atx24' })
    expect(state.cableEnds.atx24.mb_atx24).toBeUndefined()
    expect(state.connections.atx24).toHaveLength(2)
  })
  it('mantém pontas soltas fora da área do botão frontal', () => {
    const state = createHardwareCase('power')
    const moved = act(state, { type: 'moveCableEnd', cable: 'vga', connector: 'mb_vga', x: 830, y: 640 })
    expect(moved.cableEnds.vga.mb_vga).toEqual({ x: 830, y: 581 })
  })
  it('rompe uma ponta de cabo durante o arraste além do alcance', () => {
    let state = createHardwareCase('video')
    state = act(state, { type: 'disconnect', cable: 'ac' })
    state = act(state, { type: 'disconnectEnd', cable: 'eps8', connector: 'mb_eps8' })
    const before = state.journal.length
    state = act(state, { type: 'moveCableEnd', cable: 'eps8', connector: 'mb_eps8', x: 400, y: 255, transient: true })
    expect(state.cables.eps8.condition).toBe('good')
    expect(state.journal).toHaveLength(before)
    state = act(state, { type: 'moveCableEnd', cable: 'eps8', connector: 'mb_eps8', x: 600, y: 255, transient: true })
    expect(state.cables.eps8.condition).toBe('broken')
    expect(state.journal).toHaveLength(before + 1)
  })
  it('isola o botão defeituoso usando os pinos PWR_SW e exige reparo para concluir', () => {
    let state = createHardwareCase('power')
    state = connect(state, 'atx24', 'psu_atx24', 'mb_atx24')
    state = connect(state, 'eps8', 'psu_eps8', 'mb_eps8')
    state = connect(state, 'ac', 'wall_ac', 'psu_ac')
    state = act(state, { type: 'setPsu', on: true })
    state = act(state, { type: 'pressPower', method: 'button' })
    expect(state.lastTest?.code).toBe('no_power')
    state = prepare(state)
    state = act(state, { type: 'disconnectEnd', cable: 'front_panel', connector: 'mb_pwr_sw' })
    state = connect(state, 'ac', 'wall_ac', 'psu_ac')
    state = act(state, { type: 'setPsu', on: true })
    state = act(state, { type: 'pressPower', method: 'bridge' })
    expect(state.lastTest?.code).toBe('boot_ok')
    expect(isHardwareResolved(state)).toBe(false)
    state = prepare(state)
    state = act(state, { type: 'remove', slot: 'front_button' })
    state = act(state, { type: 'takePart', part: 'button_good' })
    state = act(state, { type: 'install', part: 'button_good', slot: 'front_button' })
    state = act(state, { type: 'connect', cable: 'front_panel', connector: 'mb_pwr_sw' })
    state = connect(state, 'ac', 'wall_ac', 'psu_ac')
    state = act(state, { type: 'setPsu', on: true })
    state = act(state, { type: 'pressPower', method: 'button' })
    expect(isHardwareResolved(state)).toBe(true)
  })

  it('revela primeiro a falha de RAM e depois a saída de vídeo inadequada', () => {
    let state = createHardwareCase('video')
    state = act(state, { type: 'setPsu', on: true })
    state = act(state, { type: 'pressPower', method: 'button' })
    expect(state.lastTest?.code).toBe('dram_error')
    state = prepare(state)
    state = act(state, { type: 'remove', slot: 'dimm_a2' })
    state = act(state, { type: 'takePart', part: 'ram_good' })
    state = act(state, { type: 'install', part: 'ram_good', slot: 'dimm_a2' })
    state = connect(state, 'ac', 'wall_ac', 'psu_ac')
    state = act(state, { type: 'setPsu', on: true })
    state = act(state, { type: 'pressPower', method: 'button' })
    expect(state.lastTest?.code).toBe('video_missing')
    state = prepare(state)
    state = act(state, { type: 'disconnect', cable: 'vga' })
    state = connect(state, 'hdmi', 'gpu_hdmi', 'monitor_hdmi')
    state = connect(state, 'ac', 'wall_ac', 'psu_ac')
    state = act(state, { type: 'setPsu', on: true })
    state = act(state, { type: 'pressPower', method: 'button' })
    expect(isHardwareResolved(state)).toBe(true)
  })

  it('distingue cabo SATA ausente de unidade defeituosa', () => {
    let state = createHardwareCase('storage')
    state = act(state, { type: 'setPsu', on: true })
    state = act(state, { type: 'pressPower', method: 'button' })
    expect(state.lastTest?.code).toBe('storage_missing')
    state = prepare(state)
    state = connect(state, 'sata_data', 'mb_sata1', 'disk_data')
    state = connect(state, 'sata_power', 'psu_sata', 'disk_power')
    state = connect(state, 'ac', 'wall_ac', 'psu_ac')
    state = act(state, { type: 'setPsu', on: true })
    state = act(state, { type: 'pressPower', method: 'button' })
    expect(state.lastTest?.code).toBe('storage_fault')
    state = prepare(state)
    state = act(state, { type: 'disconnect', cable: 'sata_data' })
    state = act(state, { type: 'disconnect', cable: 'sata_power' })
    state = act(state, { type: 'remove', slot: 'sata_bay' })
    state = act(state, { type: 'takePart', part: 'ssd_sata_good' })
    state = act(state, { type: 'install', part: 'ssd_sata_good', slot: 'sata_bay' })
    state = connect(state, 'sata_data', 'mb_sata1', 'disk_data')
    state = connect(state, 'sata_power', 'psu_sata', 'disk_power')
    state = connect(state, 'ac', 'wall_ac', 'psu_ac')
    state = act(state, { type: 'setPsu', on: true })
    state = act(state, { type: 'pressPower', method: 'button' })
    expect(isHardwareResolved(state)).toBe(true)
  })

  it('recusa slot incompatível e manutenção interna energizada sem perder peças', () => {
    let state = createHardwareCase('video')
    state = act(state, { type: 'install', part: 'ram_good', slot: 'pcie_x16' })
    expect(state.inventory).toEqual([])
    expect(state.feedback).toMatch(/incompatível/i)
    state = act(state, { type: 'remove', slot: 'dimm_a2' })
    expect(state.parts.dimm_a2).toBe('ram_faulty')
    expect(state.feedback).toMatch(/desconecte/i)
    state = act(state, { type: 'disconnect', cable: 'atx24' })
    expect(state.connections.atx24).toHaveLength(2)
    expect(state.feedback).toMatch(/desconecte/i)
  })

  it('permite instalar M.2 e exige soltar os cabos antes de remover o SSD SATA', () => {
    let state = createHardwareCase('power')
    expect(state.inventory).toEqual([])
    state = act(state, { type: 'takePart', part: 'ssd_m2' })
    state = act(state, { type: 'install', part: 'ssd_m2', slot: 'm2' })
    expect(state.parts.m2).toBe('ssd_m2')
    state = act(state, { type: 'remove', slot: 'sata_bay' })
    expect(state.parts.sata_bay).toBe('ssd_sata_good')
    expect(state.feedback).toMatch(/cabos SATA/i)
  })

  it('mantém a ordem física de cooler, CPU e cabo da placa de vídeo', () => {
    let state = createHardwareCase('power')
    state = act(state, { type: 'remove', slot: 'cpu' })
    expect(state.parts.cpu).toBe('cpu_i5')
    state = act(state, { type: 'remove', slot: 'cooler' })
    expect(state.parts.cooler).toBe('cooler_stock')
    state = act(state, { type: 'remove', slot: 'pcie_x16' })
    expect(state.parts.pcie_x16).toBe('gpu')
  })
})
